import { useUserConversationsQuery } from '@/core/apollo/generated/apollo-hooks';
import { RoomType } from '@/core/apollo/generated/graphql-schema';
import { useCurrentUserContext } from '@/domain/community/userCurrent/useCurrentUserContext';
import { displayedUnreadCount, useConversationSummaries } from '@/main/userMessaging/matrix/conversationSummaryStore';
import { toConversationMessage } from '@/main/userMessaging/matrix/toConversationMessage';
import { useUserMessagingContext } from '@/main/userMessaging/UserMessagingContext';
import { isGuidanceConversation, sortUnifiedConversations, type UnifiedConversation } from './dataMapper';
import { useUnifiedChatContext } from './UnifiedChatProvider';

// Server auto-generates names like "conversation-..." or "group-conversation-..." — ignore these
const isAutoGeneratedName = (name?: string) => !name || /^(conversation|group-conversation)-/.test(name);

/**
 * Unified conversation list. It flags the 1:1 Guidance conversation as
 * `isGuidance`/`pinned` and would sort it to the top, but that row is currently
 * dropped before it is returned — see the TEMP filter below.
 */
export const useUnifiedConversations = () => {
  const { isEnabled, isOpen, newlyCreatedConversationId, selectedRoomId } = useUserMessagingContext();
  const { guidanceVcId } = useUnifiedChatContext();
  const { userModel: currentUser } = useCurrentUserContext();

  const skip = !isEnabled || !isOpen;

  const { data, loading, error } = useUserConversationsQuery({
    skip,
    fetchPolicy: 'cache-and-network',
  });

  const listed = data?.me?.conversations?.conversations ?? [];
  // Latest message and unread count come from Matrix sync; GraphQL carries the
  // conversation list, membership and metadata.
  const summaries = useConversationSummaries(listed.flatMap(conv => (conv.room ? [conv.room.id] : [])));

  const conversations: UnifiedConversation[] = (() => {
    if (!data?.me?.conversations?.conversations) {
      return [];
    }

    const mapped = data.me.conversations.conversations
      .filter(conv => conv.room)
      .map(conv => {
        // biome-ignore lint/style/noNonNullAssertion: filtered by conv.room check above
        const room = conv.room!;
        const summary = summaries?.get(room.id);

        const members = conv.members.map(member => ({
          id: member.id,
          type: member.type,
          displayName: member.profile?.displayName ?? '',
          avatarUri: member.profile?.avatar?.uri,
          url: member.profile?.url,
        }));

        const isGroup = room.type === RoomType.ConversationGroup;
        const otherMembers = members.filter(m => m.id !== currentUser?.id);

        let displayName: string | undefined;
        if (!isGroup && otherMembers.length > 0) {
          displayName = otherMembers[0].displayName;
        } else if (!isAutoGeneratedName(room.displayName)) {
          displayName = room.displayName;
        } else {
          displayName = otherMembers.map(m => m.displayName).join(', ');
        }

        const avatarUri =
          !isGroup && otherMembers.length > 0 ? otherMembers[0].avatarUri : (room.avatarUrl ?? undefined);

        const roomDisplayName = isGroup && !isAutoGeneratedName(room.displayName) ? room.displayName : undefined;

        const isGuidance = isGuidanceConversation(members, guidanceVcId);

        return {
          id: conv.id,
          roomId: room.id,
          attachmentBucketId: room.attachmentBucketId,
          isGroup,
          displayName,
          roomDisplayName,
          avatarUri,
          unreadCount: displayedUnreadCount(summaries, room.id, selectedRoomId),
          createdDate: new Date(room.createdDate),
          lastMessage: summary?.lastMessage
            ? toConversationMessage(summary.lastMessage, {
                members,
                otherProfiles: new Map(),
                attachmentBucketId: room.attachmentBucketId,
              })
            : undefined,
          members,
          isGuidance,
          pinned: isGuidance,
        } satisfies UnifiedConversation;
      });

    // TEMP: guidance disabled — the Guidance assistant is hidden from users
    // while virtual contributors are off. Every guidance surface is derived from
    // this one list, so dropping the row here is also what removes the pin, the
    // beta badge, the synthetic intro message, the info/clear header buttons, its
    // contribution to the unread count, and the `?chat=<id>` deep link (which
    // resolves ids against this list and degrades to the default list on a miss).
    // The detection and rendering code is all kept: deleting this filter brings
    // guidance back.
    const visible = mapped.filter(conversation => !conversation.isGuidance);

    return sortUnifiedConversations(visible, newlyCreatedConversationId);
  })();

  // Per FR-033 the badge counts CONVERSATIONS that have unread messages, not the
  // sum of unread messages — matching the legacy `useUserConversations` /
  // `useUnreadConversationsCount`. (Name kept for parity with those hooks.)
  const totalUnreadCount = conversations.filter(conv => conv.unreadCount > 0).length;

  return {
    conversations,
    totalUnreadCount,
    isLoading: loading,
    error,
  };
};
